"""Extract the BLOSUM/PAM tables from the DIAMOND C++ sources.

The C++ headers under ``diamond-2.2.8/src/stats/matrices`` encode each
standard matrix as a 26x26 table over ``ARNDCQEGHILKMFPSTWYVBJZX*_`` plus a
list of published Karlin-Altschul parameters for the gap costs NCBI tabulated.

The generated ``src/matrix_data.rs`` is checked in so that building the Rust
crate never depends on the C++ tree.
"""

import pathlib
import re

MATRICES = [
    "blosum45",
    "blosum50",
    "blosum62",
    "blosum80",
    "blosum90",
    "pam30",
    "pam70",
    "pam250",
]

# NCBI's amino acid order; the trailing '_' column of the C++ tables is a
# sequence delimiter and is dropped here.
SYMBOLS = "ARNDCQEGHILKMFPSTWYVBJZX*"

NUM = r"([-\d.eE+]+)"

# Gapped rows: { gap_open, gap_extend, reserved, Lambda, K, H, alpha, beta,
#                C, alpha_v, sigma }
PARAM_RE = re.compile(
    r"\{\s*(\d+),\s*(\d+),\s*\(double\)INT2_MAX,\s*" + r"\s*,\s*".join([NUM] * 8)
)
# The first row holds the ungapped constants; only alpha and alpha_v are used
# (they feed the ALP intercepts).
UNGAPPED_RE = re.compile(
    r"\{\s*\{\s*\(double\)INT2_MAX,\s*\(double\)INT2_MAX,\s*\(double\)INT2_MAX,\s*"
    + r"\s*,\s*".join([NUM] * 8)
)
ROW_MARKER_RE = re.compile(r"/\*\s*([A-Za-z*])\s*\*/")


def parse(path):
    text = path.read_text(encoding="utf-8")
    # v = (Lambda, K, H, alpha, beta, C, alpha_v, sigma)
    params = [
        (int(a), int(b), float(v[0]), float(v[1]), float(v[3]), float(v[6]), float(v[7]))
        for a, b, *v in PARAM_RE.findall(text)
    ]
    ungapped = UNGAPPED_RE.search(text)
    if not ungapped:
        raise ValueError(f"{path.name}: ungapped constants not found")
    u = [float(v) for v in ungapped.groups()]
    ungapped = (u[3], u[6])  # alpha, alpha_v
    markers = list(ROW_MARKER_RE.finditer(text))
    # The score table starts at the first row marker; each row runs up to the
    # next marker (rows wrap over several source lines).
    rows = []
    for i, m in enumerate(markers):
        end = markers[i + 1].start() if i + 1 < len(markers) else len(text)
        body = text[m.end():end]
        vals = [int(v) for v in re.findall(r"-?\d+", body)]
        if len(vals) < 25:
            raise ValueError(f"{path.name}: row {m.group(1)} has only {len(vals)} values")
        rows.append(vals[:25])
    # The first two integers of the file are the default gap costs.
    default_gap = re.search(r"const StandardMatrix\s+\w+\s*\{\s*(\d+)\s*,\s*(\d+)", text)
    if len(rows) != 25:
        raise ValueError(f"{path.name}: expected 25 rows, got {len(rows)}")
    if not default_gap:
        raise ValueError(f"{path.name}: default gap costs not found")
    return rows, params, ungapped, (int(default_gap.group(1)), int(default_gap.group(2)))


def emit(entries):
    out = []
    out.append("// @generated by scripts/gen_matrices.py from DIAMOND 2.2.8 sources.")
    out.append("// Standard scoring matrices and their published Karlin-Altschul")
    out.append("// parameters (lambda, K) for the gap costs NCBI tabulated.")
    out.append("")
    out.append("/// Amino acid order of every table below (NCBI ordering).")
    out.append('pub const SYMBOLS: &[u8; 25] = b"ARNDCQEGHILKMFPSTWYVBJZX*";')
    out.append("")
    out.append("pub struct StdMatrix {")
    out.append("    pub name: &'static str,")
    out.append("    pub default_gap: (i32, i32),")
    out.append("    pub scores: [[i8; 25]; 25],")
    out.append("    /// (gap_open, gap_extend, lambda, K, alpha, alpha_v, sigma)")
    out.append("    pub params: &'static [(i32, i32, f64, f64, f64, f64, f64)],")
    out.append("    /// Ungapped (alpha, alpha_v) of the uppermost row.")
    out.append("    pub ungapped: (f64, f64),")
    out.append("}")
    out.append("")
    out.append("pub static MATRICES: &[StdMatrix] = &[")
    for name, rows, params, ungapped, default_gap in entries:
        out.append(
            f'    StdMatrix {{ name: "{name}", default_gap: ({default_gap[0]}, {default_gap[1]}), '
            f"ungapped: ({ungapped[0]:.6}, {ungapped[1]:.6}), scores: ["
        )
        for row in rows:
            out.append("        [" + ", ".join(str(v) for v in row) + "],")
        out.append("    ], params: &[")
        for go, ge, lam, k, alpha, alpha_v, sigma in params:
            out.append(
                f"        ({go}, {ge}, {lam:.6}, {k:.6}, {alpha:.6}, {alpha_v:.6}, {sigma:.6}),"
            )
        out.append("    ] },")
    out.append("];")
    out.append("")
    return "\n".join(out)


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    src = root / "diamond-2.2.8" / "src" / "stats" / "matrices"
    entries = []
    for name in MATRICES:
        rows, params, ungapped, default_gap = parse(src / f"{name}.h")
        entries.append(
            (name.upper().replace("BLOSUM", "BLOSUM"), rows, params, ungapped, default_gap)
        )
    text = emit(entries)
    (root / "src").mkdir(exist_ok=True)
    (root / "src" / "matrix_data.rs").write_text(text, encoding="utf-8")
    print(f"wrote {root / 'src' / 'matrix_data.rs'}: {len(entries)} matrices")


if __name__ == "__main__":
    main()
